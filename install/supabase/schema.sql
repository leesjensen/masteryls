----------------------- Tables


-- Course catalog metadata
create table if not exists public.catalog (
  id uuid primary key default gen_random_uuid(),
  "createdAt" timestamp with time zone default now(),
  "createdBy" uuid references auth.users(id) on delete set null default auth.uid(),
  title text,
  description text,
  name text,
  "gitHub" jsonb default '{}'::jsonb,
  settings jsonb default '{}'::jsonb
);

-- Profile row for each authenticated user
create table if not exists public."user" (
  id uuid not null references auth.users(id) on delete cascade,
  "createdAt" timestamp with time zone default now(),
  name text,
  email text,
  settings jsonb default '{}'::jsonb,
  primary key (id)
);

-- Role assignments (root/editor, etc.)
create table if not exists public.role (
  id bigint generated by default as identity primary key,
  "createdAt" timestamp with time zone default now(),
  "user" uuid references auth.users(id) on delete cascade,
  "right" varchar,
  object uuid references public.catalog(id) on delete cascade,
  settings jsonb default '{}'::jsonb
);

-- User enrollment in a catalog/course
create table if not exists public.enrollment (
  id uuid primary key default gen_random_uuid(),
  "createdAt" timestamp with time zone default now(),
  "learnerId" uuid references public."user"(id) on delete cascade,
  "catalogId" uuid references public.catalog(id) on delete cascade,
  progress jsonb default '{}'::jsonb,
  settings jsonb default '{}'::jsonb
);

-- Speeds the mastery-overview roster query, which scopes a course's enrollments to an
-- "enrolled between" window (catalogId + createdAt range).
create index if not exists enrollment_catalog_created_idx on public.enrollment ("catalogId", "createdAt");

-- Topic content cache with full-text search index source column
create table if not exists public.topic (
  id uuid primary key,
  "catalogId" uuid references public.catalog(id) on delete cascade,
  content text not null,
  ftsContent tsvector generated always as (to_tsvector('english', ' ' || content)) stored,
  "updatedAt" timestamp with time zone default now()
);

-- Progress/event tracking per user/topic
create table if not exists public.progress (
  id uuid primary key default gen_random_uuid(),
  "createdAt" timestamp with time zone default now(),
  "userId" uuid references public."user"(id) on delete cascade,
  "enrollmentId" uuid references public.enrollment(id) on delete cascade,
  "catalogId" uuid references public.catalog(id) on delete cascade,
  "topicId" uuid,
  "interactionId" uuid,
  duration integer,
  type varchar,
  details jsonb default '{}'::jsonb
);

-- Attendance sessions. Only course overseers can read these rows because they hold the
-- check-in code. Learners record attendance through the record_attendance RPC, which writes
-- a progress row of type 'attendance' with interactionId = attendance.id.
-- questions: [{ id, type: 'multiple-choice', prompt, choices: [] }]
create table if not exists public.attendance (
  id uuid primary key default gen_random_uuid(),
  "catalogId" uuid not null references public.catalog(id) on delete cascade,
  "createdBy" uuid references public."user"(id) on delete set null default auth.uid(),
  code char(4) not null,
  questions jsonb not null default '[]'::jsonb,
  "openedAt" timestamp with time zone not null default now(),
  "closedAt" timestamp with time zone
);

-- Term: a course-scoped, time-bounded period of instruction (semester/quarter/short block).
-- Schedules and sections live under a term. See the Term/Schedule/Section operational model.
create table if not exists public.term (
  id uuid primary key default gen_random_uuid(),
  "catalogId" uuid not null references public.catalog(id) on delete cascade,
  "createdBy" uuid references public."user"(id) on delete set null default auth.uid(),
  "createdAt" timestamp with time zone default now(),
  title text,
  "startDate" date,
  "endDate" date
);

-- Schedule: the content/delivery calendar (topics, deliverables, lectures). Metadata lives here;
-- the markdown content stays in GitHub at contentPath. legacyFileId maps a migrated
-- course.json schedule.files[] entry to its row (used by the one-time section backfill).
create table if not exists public.schedule (
  id uuid primary key default gen_random_uuid(),
  "catalogId" uuid not null references public.catalog(id) on delete cascade,
  "termId" uuid references public.term(id) on delete cascade,
  "createdBy" uuid references public."user"(id) on delete set null default auth.uid(),
  "createdAt" timestamp with time zone default now(),
  title text,
  state text default 'published',
  "startDate" date,
  "endDate" date,
  "contentPath" text,
  "legacyFileId" text
);

-- Section: a group of learners taking one schedule within a term. Attendance is enabled per
-- section (some sections are online / not in-person). A schedule may back many sections.
create table if not exists public.section (
  id uuid primary key default gen_random_uuid(),
  "catalogId" uuid not null references public.catalog(id) on delete cascade,
  "termId" uuid references public.term(id) on delete cascade,
  "scheduleId" uuid references public.schedule(id) on delete set null,
  "createdBy" uuid references public."user"(id) on delete set null default auth.uid(),
  "createdAt" timestamp with time zone default now(),
  title text,
  state text default 'active',
  "attendanceEnabled" boolean not null default false,
  "legacyFileId" text
);

-- Archived AI course/section/learner pulses. The "Pulse N" label is derived from creation order at
-- read time (see service.getPulses) - there is no stored number, so no number-sequencing RPC.
create table if not exists public.pulse (
  id uuid primary key default gen_random_uuid(),
  "catalogId" uuid not null references public.catalog(id) on delete cascade,
  "termId" uuid not null references public.term(id) on delete cascade,
  "targetType" text not null check ("targetType" in ('course', 'section', 'learner')),
  "targetId" uuid not null,
  "enrollmentId" uuid references public.enrollment(id) on delete cascade,
  "pulseType" text not null default 'pulse' check ("pulseType" in ('pulse', 'feedback')),
  markdown text not null,
  "createdBy" uuid not null references public."user"(id),
  "createdAt" timestamptz not null default now()
);
create index if not exists pulse_target_created_idx on public.pulse ("catalogId", "termId", "targetType", "targetId", "createdAt" desc);

-- Associate each enrollment with a section (nullable: a course may have no sections, and legacy
-- enrollments are backfilled). The learner's schedule is derived via section -> schedule. Added
-- after the section table so the FK resolves on a fresh install.
alter table public.enrollment
  add column if not exists "sectionId" uuid references public.section(id) on delete set null;

-- Attendance sessions are taken per section (some sections are online / not in-person). Added after
-- the section table so the FK resolves on a fresh install. Legacy sessions keep sectionId null.
alter table public.attendance
  add column if not exists "sectionId" uuid references public.section(id) on delete set null;

