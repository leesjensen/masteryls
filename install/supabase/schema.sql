-- RPC: close an attendance session
create or replace function public.close_attendance(p_session_id uuid)
returns public.attendance
language plpgsql
security definer
set search_path = public
as $$
declare
  v_session public.attendance%rowtype;
begin
  select * into v_session from public.attendance where id = p_session_id;
  if not found then
    raise exception 'Attendance session not found';
  end if;

  if not public.auth_oversees_course(auth.uid(), v_session."catalogId") then
    raise exception 'User is not authorized to take attendance for this course';
  end if;

  update public.attendance
  set "closedAt" = coalesce("closedAt", now())
  where id = p_session_id
  returning * into v_session;

  return v_session;
end;
$$;

-- RPC: record the caller's attendance for the course's open session. The code must match.
-- If the session has questions and no answers were provided, the questions are returned
-- (status 'questions') without recording anything so the client can ask them and resubmit.
create or replace function public.record_attendance(p_catalog_id uuid, p_code text, p_answers jsonb default null)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_enrollment public.enrollment%rowtype;
  v_session public.attendance%rowtype;
  v_attended integer;
  v_status text := 'recorded';
begin
  select * into v_enrollment
  from public.enrollment
  where "catalogId" = p_catalog_id
    and "learnerId" = v_user_id
  limit 1;

  if not found then
    raise exception 'You must be enrolled in this course to record attendance';
  end if;

  select * into v_session
  from public.attendance
  where "catalogId" = p_catalog_id
    and "closedAt" is null
    and code = trim(coalesce(p_code, ''));

  if not found then
    raise exception 'No attendance is being taken with that code';
  end if;

  if exists (
    select 1 from public.progress
    where "enrollmentId" = v_enrollment.id
      and type = 'attendance'
      and "interactionId" = v_session.id
  ) then
    v_status := 'alreadyRecorded';
  elsif jsonb_array_length(v_session.questions) > 0 and p_answers is null then
    return jsonb_build_object('status', 'questions', 'sessionId', v_session.id, 'questions', v_session.questions);
  else
    insert into public.progress ("userId", "catalogId", "enrollmentId", "interactionId", type, details)
    values (
      v_user_id,
      p_catalog_id,
      v_enrollment.id,
      v_session.id,
      'attendance',
      jsonb_build_object('answers', case when jsonb_typeof(p_answers) = 'object' then p_answers else '{}'::jsonb end)
    )
    on conflict ("enrollmentId", "interactionId") where type = 'attendance' do nothing;
  end if;

  select count(distinct "interactionId") into v_attended
  from public.progress
  where "enrollmentId" = v_enrollment.id
    and type = 'attendance';

  return jsonb_build_object('status', v_status, 'sessionId', v_session.id, 'attended', v_attended);
end;
$$;

-- RPC: attendance sessions for a course (without codes) with attendee counts. Available to
-- enrolled learners and course overseers so attendance history can be graphed. When p_section_id is
-- given the result is scoped to that section (sessions and the enrolledCount denominator), so the
-- learner chart can show an honest "attended N of M"; null returns the whole course.
drop function if exists public.attendance_sessions(uuid);
create or replace function public.attendance_sessions(p_catalog_id uuid, p_section_id uuid default null)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
begin
  if not (
    public.auth_oversees_course(v_user_id, p_catalog_id)
    or exists (select 1 from public.enrollment where "catalogId" = p_catalog_id and "learnerId" = v_user_id)
  ) then
    raise exception 'User is not authorized to view attendance for this course';
  end if;

  return jsonb_build_object(
    'enrolledCount', (select count(*) from public.enrollment where "catalogId" = p_catalog_id and (p_section_id is null or "sectionId" = p_section_id)),
    'sessions', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', a.id,
        'openedAt', a."openedAt",
        'closedAt', a."closedAt",
        'questions', a.questions,
        'attendeeCount', (
          select count(distinct p."userId")
          from public.progress p
          where p."catalogId" = a."catalogId"
            and p.type = 'attendance'
            and p."interactionId" = a.id
        ),
        -- Per-question answer counts for this session: { [questionId]: { [choice]: count } }.
        -- Lets the attendance charts show how the class answered the wellness question.
        'answerTally', (
          select coalesce(jsonb_object_agg(per_q.qid, per_q.counts), '{}'::jsonb)
          from (
            select ans.qid, jsonb_object_agg(ans.answer, ans.c) as counts
            from (
              select kv.key as qid, kv.value as answer, count(*)::int as c
              from public.progress p
              cross join lateral jsonb_each_text(coalesce(p.details -> 'answers', '{}'::jsonb)) as kv(key, value)
              where p."catalogId" = a."catalogId"
                and p.type = 'attendance'
                and p."interactionId" = a.id
              group by kv.key, kv.value
            ) ans
            group by ans.qid
          ) per_q
        )
      ) order by a."openedAt")
      from public.attendance a
      where a."catalogId" = p_catalog_id
        and (p_section_id is null or a."sectionId" = p_section_id)
    ), '[]'::jsonb)
  );
end;
$$;

-- RPC for free-text topic search with highlighted snippets
create or replace function public.search_topics(search_query text, target_catalog_id uuid default null)
returns table (
  id uuid,
  "catalogId" uuid,
  headline text,
  rank real
)
language plpgsql
as $$
begin
  return query
  select
    t.id,
    t."catalogId",
    ts_headline(
      'english',
      t.content,
      websearch_to_tsquery('english', search_query),
      'StartSel="<mark>", StopSel="</mark>", MaxWords=10, MinWords=5, MaxFragments=3, FragmentDelimiter=" ... "'
    ) as headline,
    ts_rank(t."ftsContent", websearch_to_tsquery('english', search_query)) as rank
  from public.topic t
  where t."ftsContent" @@ websearch_to_tsquery('english', search_query)
    and (target_catalog_id is null or t."catalogId" = target_catalog_id)
  order by rank desc;
end;
$$;

-- Security helper: true when user has root role
create or replace function public.auth_is_root(uid uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.role
    where "user" = uid
      and "right" = 'root'
  );
$$;

